#!/usr/bin/env python3
"""Scan ``$HOME`` and write ``FILE-TYPES.org``: which extensions have icons.

The mapping is read from the theme itself: the shipped mimetype icons are
grouped by the artwork they share (byte-identical renders), so every name that
draws the same picture ends up in one family, and any name of the form
``application-x-<ext>`` contributes its extension.  This script counts the files
actually present, so the report is measured rather than guessed.

    python3 tools/report_file_types.py
    python3 tools/report_file_types.py --root ~ --out FILE-TYPES.org
"""

from __future__ import annotations

import argparse
import hashlib
import os
import re
import sys
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
THEME = ROOT / "skeu-icons"
MIME_DIR = THEME / "scalable" / "mimetypes"
SAMPLE_DIR = THEME / "16x16" / "mimetypes"

EXT_RE = re.compile(r"^[a-z0-9][a-z0-9_+.-]{0,11}$")
FALLBACK = "application-x-"


def scan(root: Path) -> Counter:
    """Count files per lower-case extension, without following symlinks."""
    counts: Counter = Counter()
    for directory, _dirs, files in os.walk(root, followlinks=False):
        for name in files:
            base = name.rsplit("/", 1)[-1]
            if "." not in base:
                continue
            ext = base.rsplit(".", 1)[-1].lower()
            if EXT_RE.match(ext):
                counts[ext] += 1
    return counts


def digest(path: Path) -> str:
    return hashlib.sha1(path.read_bytes()).hexdigest()


def families() -> list[tuple[str, list[str]]]:
    """``(icon name, extensions)`` for every artwork family shipped in the theme."""
    groups: dict[str, list[str]] = defaultdict(list)
    for svg in sorted(MIME_DIR.glob("*.svg")):
        sample = SAMPLE_DIR / f"{svg.stem}.png"
        groups[digest(sample) if sample.is_file() else svg.stem].append(svg.stem)

    rows = []
    for names in groups.values():
        exts = sorted(n[len(FALLBACK):] for n in names if n.startswith(FALLBACK))
        if not exts:
            continue
        labels = [n for n in names if not n.startswith(FALLBACK)] or names
        rows.append((min(labels, key=len), exts))
    return rows


def wrap(extensions: list[str], width: int = 74) -> str:
    lines, line = [], ""
    for ext in extensions:
        piece = (", " if line else "") + ext
        if len(line) + len(piece) > width:
            lines.append(line + ",")
            line = ext
        else:
            line += piece
    if line:
        lines.append(line)
    return "\n".join(lines)


def build(root: Path) -> str:
    counts = scan(root)
    fams = []
    covered: set[str] = set()
    for icon, exts in families():
        covered.update(exts)
        fams.append((sum(counts[e] for e in exts), icon, exts))
    fams.sort(key=lambda row: (-row[0], row[1]))
    total_files = sum(counts.values())
    uncovered = sorted(set(counts) - covered, key=lambda e: -counts[e])

    lines = [
        "#+title: File types",
        "#+options: toc:2",
        "",
        "Every file extension found under the home directory, and the icon the",
        "theme ships for it. Generated by [[file:tools/report_file_types.py][tools/report_file_types.py]]; the mapping",
        "is read from the shipped theme (=skeu-icons/scalable/mimetypes=), so it can",
        "never drift from the artwork.",
        "",
        "** The scan",
        "",
        f"* scanned: ={root}=",
        f"* files with an extension: *{total_files:,}*",
        f"* distinct extensions: *{len(counts):,}*",
        f"* extensions with an icon: *{len(covered):,}*",
        f"* extensions without one: *{len(uncovered):,}* (build output, caches, temporaries)",
        "",
        "Each extension gets two names in the theme: the freedesktop name for its",
        "mime type (=text-x-python=) and the fallback file managers ask for",
        "(=application-x-py=). Both are the same render, so one drawing serves a",
        "whole family of extensions.",
        "",
        "** Icons by family",
        "",
        "| files | icon | extensions |",
        "|------:|------|------------|",
    ]
    for files, icon, exts in fams:
        lines.append(f"| {files:>6,} | {icon} | {', '.join(exts)} |")
    lines += [
        "",
        "** Extensions without an icon",
        "",
        "These are build artefacts, caches and temporaries rather than documents:",
        "",
        "#+begin_example",
        wrap(uncovered),
        "#+end_example",
        "",
        "** Regenerating",
        "",
        "#+begin_src sh",
        "python3 tools/report_file_types.py      # rewrites this file",
        "#+end_src",
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", default=str(Path.home()))
    parser.add_argument("--out", default=str(ROOT / "FILE-TYPES.org"))
    args = parser.parse_args(argv)
    text = build(Path(args.root).expanduser())
    Path(args.out).write_text(text)
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
